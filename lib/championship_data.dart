/// 配件耗电：低/高组（按星级：1-2 星 1/2，3-5 星 2/3）
int champGadgetDrain(int tier, {required bool highGroup}) {
  final star = champStarOf(tier);
  final low = star <= 2 ? 1 : 2;
  return highGroup ? low + 1 : low;
}
