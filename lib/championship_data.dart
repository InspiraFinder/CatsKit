    '${kChampMaterialZh[champMaterialOf(tier)]} ${champStarOf(tier)} 星';
String champTierNameEn(int tier) {
  final s = champStarOf(tier);
  return '${kChampMaterialEn[champMaterialOf(tier)]} $s ${s == 1 ? 'star' : 'stars'}';
}

